#!/usr/bin/env node
// DERIVED FILE GENERATOR - writes catalog/index.html from the manifest, the
// token source and each component's spec. Never hand-edit the output.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const EXT = "com.multicode";
const manifest = JSON.parse(readFileSync(join(ROOT, "design-system.json"), "utf8"));
const tree = JSON.parse(readFileSync(join(ROOT, "foundations/tokens.tokens.json"), "utf8"));

const esc = (s) =>
  String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);

const tokens = [];
(function walk(node, path = []) {
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith("$")) continue;
    if (value && typeof value === "object") {
      if ("$value" in value) tokens.push({ path: [...path, key].join("."), token: value });
      else walk(value, [...path, key]);
    }
  }
})(tree);

const typeOf = (path) => {
  const parts = path.split(".");
  for (let i = parts.length; i > 0; i--) {
    const node = parts.slice(0, i).reduce((n, k) => n?.[k], tree);
    if (node?.$type) return node.$type;
  }
};
const cssVar = (path) =>
  `--${path.replace(/\./g, "-").replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase()}`;

/** Group tokens by their first two segments, in source order. */
const groups = new Map();
for (const t of tokens) {
  const key = t.path.split(".").slice(0, 2).join(".");
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(t);
}

const swatch = (t) => {
  const type = typeOf(t.path);
  const v = cssVar(t.path);
  if (type === "color")
    return `<i class="sw sw--color" style="background: var(${v})"></i>`;
  if (type === "gradient")
    return `<i class="sw sw--grad" style="background: var(${v})"></i>`;
  if (type === "shadow")
    return `<i class="sw sw--shadow" style="box-shadow: var(${v})"></i>`;
  if (type === "dimension")
    return `<i class="sw sw--dim"><b style="width: var(${v})"></b></i>`;
  return `<i class="sw sw--none"></i>`;
};

const tokenRows = [...groups]
  .map(([group, list]) => {
    const rows = list
      .map((t) => {
        const meta = t.token.$extensions?.[EXT];
        const modes = meta?.modes ? ` <em class="modal">light / dark</em>` : "";
        return `<tr>
  <td>${swatch(t)}</td>
  <th><code>${esc(cssVar(t.path))}</code>${modes}</th>
  <td class="desc">${esc(t.token.$description ?? "")}${
    meta?.use ? `<em>${esc(meta.use)}</em>` : ""
  }</td>
</tr>`;
      })
      .join("\n");
    return `<h3 id="t-${esc(group)}">${esc(group)} <span>${list.length}</span></h3>
<table class="tokens">${rows}</table>`;
  })
  .join("\n");

const inline = (s) =>
  esc(s)
    .replace(/`([^`]+)`/g, "<code>$1</code>")
    .replace(/\*([^*]+)\*/g, "<em>$1</em>")
    .replace(/ - /, " &mdash; ");

const components = (manifest.contents?.components ?? []).map((name) => {
  const mdPath = join(ROOT, name, "component.md");
  const md = existsSync(mdPath) ? readFileSync(mdPath, "utf8") : "";
  const title = md.match(/^#\s+(.+)$/m)?.[1] ?? name;
  const blurb = md.split(/\n## /)[0].split("\n").slice(1).join(" ").trim();
  // Split on the headings rather than regex-matching to the next one: `$` under
  // the `m` flag matches end-of-LINE, which truncated every section to one bullet.
  const sections = Object.fromEntries(
    md.split(/^## /m).slice(1).map((chunk) => {
      const nl = chunk.indexOf("\n");
      return [chunk.slice(0, nl).trim(), chunk.slice(nl + 1).trim()];
    }),
  );
  const section = (h) => sections[h] ?? "";
  // Join wrapped continuation lines back onto their bullet before splitting.
  const bullets = (h) =>
    section(h)
      .replace(/\n {2,}(?=\S)/g, " ")
      .split("\n")
      .filter((l) => l.startsWith("- "))
      .map((l) => l.slice(2).trim());
  return { name, title, blurb, variants: bullets("Variants"), states: bullets("States") };
});

const cards = components
  .map(
    (c) => `<article class="card">
  <h3><a href="../${esc(c.name)}/component.html">${esc(c.title)}</a></h3>
  <p>${inline(c.blurb)}</p>
  <dl>
    <dt>Variants</dt><dd>${c.variants.length}</dd>
    <dt>States</dt><dd>${c.states.length}</dd>
  </dl>
  <ul>${c.variants.map((v) => `<li>${inline(v)}</li>`).join("")}</ul>
  <p class="open"><a href="../${esc(c.name)}/component.html">Open the demo &rarr;</a></p>
</article>`,
  )
  .join("\n");

const modeVarying = tokens.filter((t) => t.token.$extensions?.[EXT]?.modes).length;

const html = `<!doctype html>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${esc(manifest.name)} ${esc(manifest.version)} - catalog</title>
<!-- GENERATED by scripts/build-catalog.mjs. Do not edit. -->
<link rel="stylesheet" href="../foundations/tokens.css" />
<style>
  body {
    margin: 0; padding: 40px 24px 80px;
    background: var(--sem-color-surface-solid);
    color: var(--sem-color-text-primary);
    font: var(--sem-text-body-font-weight) var(--sem-text-body-font-size) /
      var(--sem-text-body-line-height) var(--sem-text-body-font-family);
  }
  .wrap { max-width: 960px; margin: 0 auto; }
  h1 { font-size: var(--sem-text-title-font-size); letter-spacing: var(--sem-text-title-letter-spacing); margin: 0 0 4px; }
  .sub { color: var(--sem-color-text-muted); margin: 0 0 8px; }
  .counts { color: var(--sem-color-text-muted); font-size: var(--sem-text-caption-font-size); margin: 0 0 40px; }
  h2 {
    font-size: var(--sem-text-eyebrow-font-size); text-transform: uppercase;
    letter-spacing: var(--sem-text-eyebrow-letter-spacing); color: var(--sem-color-text-muted);
    border-top: 1px solid var(--sem-color-border-hairline); padding-top: 16px; margin: 48px 0 16px;
  }
  h3 { font-size: var(--sem-text-body-font-size); margin: 28px 0 8px; }
  h3 span { color: var(--sem-color-text-muted); font-weight: 400; }
  .grid { display: grid; gap: 16px; grid-template-columns: repeat(auto-fill, minmax(260px, 1fr)); }
  .card {
    background: var(--sem-color-surface-raised); border-radius: var(--sem-radius-surface);
    padding: 20px; border: 1px solid var(--sem-color-border-hairline);
  }
  .card h3 { margin: 0 0 6px; font-size: var(--ref-font-size-xl); }
  .card a { color: inherit; }
  .card p { margin: 0 0 12px; color: var(--sem-color-text-secondary); font-size: var(--sem-text-caption-font-size); }
  .card dl { margin: 0 0 12px; font-size: var(--sem-text-caption-font-size); }
  .card dt, .card dd { display: inline; }
  .card dt { color: var(--sem-color-text-muted); }
  .card dt::after { content: " "; }
  .card dd { margin: 0 12px 0 0; font-weight: 600; }
  .card ul { margin: 0; padding-left: 18px; font-size: var(--sem-text-caption-font-size); color: var(--sem-color-text-secondary); }
  .card li { margin-bottom: 4px; }
  .open { margin: 12px 0 0 !important; }
  .open a { color: var(--sem-color-action-quiet); font-weight: 600; text-decoration: none; }
  table.tokens { width: 100%; border-collapse: collapse; }
  table.tokens td, table.tokens th { border-bottom: 1px solid var(--sem-color-border-hairline); padding: 7px 8px; text-align: left; vertical-align: top; font-weight: 400; }
  table.tokens th { width: 32%; }
  code { font-family: ui-monospace, SFMono-Regular, Menlo, monospace; font-size: 11px; }
  .desc { color: var(--sem-color-text-secondary); font-size: var(--sem-text-caption-font-size); }
  .desc em { display: block; color: var(--sem-color-text-muted); font-style: normal; margin-top: 2px; }
  .modal { display: block; font-style: normal; font-size: 9px; color: var(--sem-color-text-muted); text-transform: uppercase; letter-spacing: 1px; }
  .sw { display: block; width: 34px; height: 20px; border-radius: 4px; }
  .sw--color, .sw--grad { border: 1px solid var(--sem-color-border-hairline); }
  .sw--shadow { background: var(--sem-color-surface-raised); }
  .sw--dim { background: none; display: flex; align-items: center; }
  .sw--dim b { display: block; height: 8px; min-width: 1px; background: var(--sem-color-action-quiet); border-radius: 2px; }
  @media (max-width: 640px) { table.tokens th { width: auto; } }
</style>
<div class="wrap">
  <h1>${esc(manifest.name)}</h1>
  <p class="sub">${esc(manifest.description ?? "")}</p>
  <p class="counts">
    v${esc(manifest.version)} &middot; schema ${esc(manifest.schemaVersion)} &middot;
    ${tokens.length} tokens (${modeVarying} mode-varying) &middot;
    ${components.length} components &middot; modes: ${manifest.modes.map(esc).join(", ")}
  </p>

  <h2>Components</h2>
  <div class="grid">
${cards}
  </div>

  <h2>Tokens</h2>
${tokenRows}
</div>
`;

writeFileSync(join(ROOT, "catalog/index.html"), html);
console.log(`catalog/index.html: ${components.length} components, ${tokens.length} tokens`);
