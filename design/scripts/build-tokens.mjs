#!/usr/bin/env node
// DERIVED FILE GENERATOR - writes foundations/tokens.css from foundations/tokens.tokens.json.
// Never hand-edit the output. Run twice and diff: the output must be byte-identical.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "foundations/tokens.tokens.json");
const OUT = join(ROOT, "foundations/tokens.css");
const EXT = "com.multicode";

const tree = JSON.parse(readFileSync(SRC, "utf8"));

/** Walk in source order so the output is stable. */
function* walk(node, path = []) {
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith("$")) continue;
    if (value && typeof value === "object") {
      if ("$value" in value) yield { path: [...path, key], token: value };
      else yield* walk(value, [...path, key]);
    }
  }
}

const tokens = new Map();
for (const { path, token } of walk(tree)) tokens.set(path.join("."), token);

/** Inherit $type from the nearest ancestor group that declares one. */
function typeOf(path) {
  const parts = path.split(".");
  for (let i = parts.length; i > 0; i--) {
    const node = parts.slice(0, i).reduce((n, k) => n?.[k], tree);
    if (node?.$type) return node.$type;
  }
  return undefined;
}

const ALIAS = /^\{([A-Za-z0-9_.-]+)\}$/;
function resolve(value, mode, seen = new Set()) {
  if (typeof value === "string") {
    const m = value.match(ALIAS);
    if (!m) return value;
    if (seen.has(m[1])) throw new Error(`Alias cycle at {${m[1]}}`);
    const target = tokens.get(m[1]);
    if (!target) throw new Error(`Alias {${m[1]}} does not resolve to a token`);
    return resolve(valueFor(target, mode), mode, new Set([...seen, m[1]]));
  }
  if (Array.isArray(value)) return value.map((v) => resolve(v, mode, seen));
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([k, v]) => [k, resolve(v, mode, seen)]),
    );
  }
  return value;
}

/** A token's raw value for a mode, before aliases are followed. */
function valueFor(token, mode) {
  const modes = token.$extensions?.[EXT]?.modes;
  if (modes && mode in modes) return modes[mode];
  return token.$value;
}

const varName = (path) =>
  `--${path.replace(/\./g, "-").replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase()}`;

const quoteFamily = (list) =>
  (Array.isArray(list) ? list : [list])
    .map((f) => (/[^a-zA-Z0-9-]/.test(f) ? `"${f}"` : f))
    .join(", ");

const shadowCss = (s) =>
  (Array.isArray(s) ? s : [s])
    .map((v) => `${v.offsetX} ${v.offsetY} ${v.blur}${v.spread && v.spread !== "0px" ? ` ${v.spread}` : ""} ${v.color}`)
    .join(", ");

/** One token can emit several custom properties (typography is composite). */
function declarations(path, token, mode) {
  const type = typeOf(path);
  const value = resolve(valueFor(token, mode), mode);
  const name = varName(path);
  if (type === "typography") {
    const map = {
      fontFamily: "font-family",
      fontSize: "font-size",
      fontWeight: "font-weight",
      letterSpacing: "letter-spacing",
      lineHeight: "line-height",
    };
    return Object.entries(value).map(([k, v]) => [
      `${name}-${map[k] ?? k}`,
      k === "fontFamily" ? quoteFamily(v) : String(v),
    ]);
  }
  if (type === "shadow") return [[name, shadowCss(value)]];
  if (type === "gradient")
    return [[
      name,
      `linear-gradient(90deg, ${value
        .map((s) => `${s.color} ${(s.position * 100).toFixed(2).replace(/\.?0+$/, "")}%`)
        .join(", ")})`,
    ]];
  if (type === "fontFamily") return [[name, quoteFamily(value)]];
  return [[name, String(value)]];
}

/** Does this token, or anything it aliases through, change between modes? */
function varies(token, seen = new Set()) {
  if (token.$extensions?.[EXT]?.modes) return true;
  const check = (v) => {
    if (typeof v === "string") {
      const m = v.match(ALIAS);
      if (m && !seen.has(m[1])) {
        const t = tokens.get(m[1]);
        return t ? varies(t, new Set([...seen, m[1]])) : false;
      }
      return false;
    }
    if (Array.isArray(v)) return v.some(check);
    if (v && typeof v === "object") return Object.values(v).some(check);
    return false;
  };
  return check(token.$value);
}

const all = [...tokens];
const modeVarying = all.filter(([, t]) => varies(t));

const emit = (entries, mode, indent) =>
  entries
    .flatMap(([path, token]) => declarations(path, token, mode))
    .map(([name, value]) => `${indent}${name}: ${value};`)
    .join("\n");

const header = `/* GENERATED by scripts/build-tokens.mjs from foundations/tokens.tokens.json. Do not edit.
 * ${all.length} tokens, ${modeVarying.length} of them mode-varying.
 * Light is the default. Dark applies on [data-mode="dark"] and, unless a
 * [data-mode="light"] ancestor opts out, on prefers-color-scheme: dark. */`;

const css = `${header}

:root {
${emit(all, "light", "  ")}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-mode="light"]) {
${emit(modeVarying, "dark", "    ")}
  }
}

[data-mode="dark"] {
${emit(modeVarying, "dark", "  ")}
}

[data-mode="light"] {
${emit(modeVarying, "light", "  ")}
}
`;

writeFileSync(OUT, css);
console.log(`tokens.css: ${all.length} tokens (${modeVarying.length} mode-varying)`);
