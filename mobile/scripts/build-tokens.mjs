#!/usr/bin/env node
/**
 * The app's colours, type scale and spacing are the site's: this reads every
 * custom property in ui/theme.css and writes src/theme/css.generated.ts, so a
 * colour changed for the site is changed for the app on the next build.
 *
 *   node scripts/build-tokens.mjs           write it
 *   node scripts/build-tokens.mjs --check   fail if it is out of date (CI)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const mobile = join(dirname(fileURLToPath(import.meta.url)), "..");
const css = readFileSync(join(mobile, "..", "ui", "theme.css"), "utf8");
const target = join(mobile, "src", "theme", "css.generated.ts");

const values = new Map();
// Only plain values: colours, lengths, numbers. var() and calc() chains are
// the site's composition, not tokens the app reads.
for (const [, name, value] of css.matchAll(/^\s*--([a-z0-9-]+):\s*([^;]+);/gim)) {
  const v = value.trim();
  if (/var\(|calc\(|\{/.test(v)) continue;
  if (!values.has(name)) values.set(name, v);
}

const body = [...values]
  .map(([name, value]) => `  ${JSON.stringify(name)}: ${JSON.stringify(value)},`)
  .join("\n");
const out = `// Generated by scripts/build-tokens.mjs from ui/theme.css. Do not edit.
export const css = {
${body}
} as const;

export type CssToken = keyof typeof css;
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== out) {
    console.error("src/theme/css.generated.ts is out of date: run npm run tokens");
    process.exit(1);
  }
  console.log(`tokens: ${values.size} current`);
} else {
  writeFileSync(target, out);
  console.log(`tokens: wrote ${values.size}`);
}
