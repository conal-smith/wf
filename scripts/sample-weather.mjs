function frameHours(model) {
  if (model.stepRanges) {
    const hours = [0];
    let end = 0;
    for (const range of model.stepRanges) {
      for (
        let h = end + range.stepHours;
        h <= range.throughHour;
        h += range.stepHours
      )
        hours.push(h);
      end = range.throughHour;
    }
    return hours;
  }
  const hours = [];
  for (let h = 0; h <= model.horizonHours; h += model.stepHours) hours.push(h);
  return hours;
}

/** What a real manifest says about where its numbers came from. */
const provenance = () => ({
  sourceUrl: SYNTHETIC.sourceUrl,
  attribution: SYNTHETIC.attribution,
  licenseUrl: SYNTHETIC.licenseUrl,
  processing: SYNTHETIC.note,
});

/**
 * The window a frame's gust maximum covers, as each adapter publishes it: a
 * point value for an instantaneous gust, otherwise a named short window while
 * the source still publishes one, widening to the step beyond that.
 */
function gustInterval(model, hours, index) {
  const hour = hours[index];
  if (model.gust === "instantaneous") return [hour, hour];
  if (hour === 0) return [0, 0];
  const step = hour - hours[index - 1];
  const window =
    model.gustWindowHours !== undefined &&
    (model.gustShortThroughHour === undefined ||
      hour <= model.gustShortThroughHour)
      ? Math.min(model.gustWindowHours, step)
      : step;
  return [hour - window, hour];
}

function windBundle(model, spots, runMs, grid) {
  const run = runId(runMs);
  const hours = frameHours(model);
  const prefix = `${model.id}-${run}-${hours[hours.length - 1]}h-v1`;
  const series = Object.fromEntries(spots.map((spot) => [spot.id, []]));
  const frames = [];
  const files = [];
  hours.forEach((hour, index) => {
    const planes = {
      u: plane(grid, WIND.u, hour, model.seed),
      v: plane(grid, WIND.v, hour, model.seed + 0.37),
      gust: plane(grid, WIND.gust, hour, model.seed + 0.73),
    };
    const gustMissing =
      model.gust === "none" || (model.gust === "fromHourOne" && hour === 0);
    const interval = gustMissing ? null : gustInterval(model, hours, index);
    const valid = iso(runMs + hour * HOUR);
    const payload = {
      model: model.id,
      run,
      hour,
      validTime: valid,
      grid,
      gustIntervalHours: interval,
      u: bounded(field(grid, planes.u), 150, null, `${model.id} u`),
      v: bounded(field(grid, planes.v), 150, null, `${model.id} v`),
      gust: gustMissing
        ? null
        : bounded(field(grid, planes.gust), 150, 0, `${model.id} gust`),
    };
    // A binary bundle hashes the bytes it publishes, exactly as the adapters do;
    // a JSON one keeps hashing its payload, so the legacy path stays covered.
    const body =
      model.encoding === F5_ENCODING ? encodeFrame(payload) : payload;
    const suffix = model.encoding === F5_ENCODING ? "bin" : "json";
    const url = `weather/${prefix}/${pad(hour, 3)}-${digestOf(body)}.${suffix}`;
    files.push([url, body]);
    frames.push({ hour, validTime: valid, url, gustIntervalHours: interval });
    for (const spot of spots) {
      const x = spotX(grid, spot.lon);
      const y = spotY(grid, spot.lat);
      series[spot.id].push({
        hour,
        validTime: valid,
        u: q2(planeAt(planes.u, x, y)),
        v: q2(planeAt(planes.v, x, y)),
        gust: gustMissing ? null : q2(planeAt(planes.gust, x, y)),
      });
    }
  });
  const manifest = {
    schemaVersion: 1,
    model: model.id,
    modelName: model.name,
    provider: SYNTHETIC.provider,
    resolutionKm: model.resolutionKm,
    resolutionLabel: `${grid.dx}° sample grid`,
    modelDetail: `${model.name} shaped sample bundle`,
    run,
    runTime: iso(runMs),
    generatedAt: iso(runMs),
    stepHours: model.stepHours,
    ...(model.stepRanges ? { stepRanges: model.stepRanges } : {}),
    grid,
    ...(model.encoding ? { encoding: model.encoding } : {}),
    frames,
    spotForecasts: series,
    ...(model.gust === "none" ? { gustAvailable: false } : {}),
    ...(model.gust === "fromHourOne" ? { gustMissingHours: [0] } : {}),
    ...(model.gust === "instantaneous" ? { gustKind: "instantaneous" } : {}),
    gustDescription:
      model.gust === "none"
        ? "This sample bundle publishes no gust field."
        : "Sample gusts: a smooth analytic field, not a forecast.",
    ...provenance(),
  };
  return { manifest, files };
}

function waveBundle(model, spots, runMs, grid) {
  const run = runId(runMs);
  const hours = frameHours(model);
  const prefix = `${model.id}-${run}-${hours[hours.length - 1]}h-v1`;
  const names = Object.keys(WAVE_VARIABLES);
  const mask = new Array(grid.width * grid.height).fill(false);
  for (const [id, treatment] of Object.entries(WAVE_COVERAGE)) {
    if (treatment !== "masked") continue;
    const spot = spots.find((entry) => entry.id === id);
    if (spot) for (const index of maskCells(grid, spot)) mask[index] = true;
  }
  // Only the deliberately masked locations may lose their series to the mask.
  const resolved = new Map(
    spots.map((spot) => {
      const stencil = corners(grid, spot.lon, spot.lat);
      const wet = stencil !== null && stencil.every((index) => !mask[index]);
      if (wet === (WAVE_COVERAGE[spot.id] === "masked"))
        throw new Error(
          `Wave mask does not match the declared coverage for ${spot.id}`,
        );
      return [spot.id, wet];
    }),
  );

  const series = Object.fromEntries(spots.map((spot) => [spot.id, []]));
  const frames = [];
  const files = [];
  for (const hour of hours) {
    const valid = iso(runMs + hour * HOUR);
    const fields = {};
    const planes = {};
    for (const [name, variable] of Object.entries(WAVE_VARIABLES)) {
      planes[name] = plane(
        grid,
        variable.spec,
        hour,
        model.seed + names.indexOf(name) * 0.11,
      );
      // A partition only exists where the source separated one. This bundle
      // separates the first swell at initialization and nowhere else, which is
      // how a real run reads: a sparser row of dashes, never a row of zeroes.
      fields[name] = bounded(
        separated(name, hour)
          ? field(grid, planes[name], 2, mask)
          : new Array(grid.width * grid.height).fill(null),
        1000,
        null,
        `${model.id} ${name}`,
      );
    }
    const payload = {
      model: model.id,
      run,
      hour,
      validTime: valid,
      grid,
      ...fields,
    };
    const url = `weather/${prefix}/${pad(hour, 3)}-${digestOf(payload)}.json`;
    files.push([url, payload]);
    frames.push({ hour, validTime: valid, url });
    for (const spot of spots) {
      const wet = resolved.get(spot.id);
      const x = spotX(grid, spot.lon);
      const y = spotY(grid, spot.lat);
      series[spot.id].push({
        hour,
        validTime: valid,
        values: Object.fromEntries(
          names.map((name) => [
            name,
            wet && separated(name, hour)
              ? q2(planeAt(planes[name], x, y))
              : null,
          ]),
        ),
      });
    }
  }
  const coverage = Object.fromEntries(
    spots.map((spot) => {
      const treatment = WAVE_COVERAGE[spot.id] ?? "water";
      const note =
        treatment === "masked"
          ? "The sample cell over this location, and every cell reaching it, is land, ice or unresolved. This model cannot say anything about waves here."
          : treatment === "nearby"
            ? "The sample cell over this location is land, ice or unresolved; the values come from the resolved water next to it, so they describe the nearby open sea rather than the shoreline itself."
            : "This location sits in a resolved water cell of the sample grid.";
      return [
        spot.id,
        {
          landMasked: treatment !== "water",
          resolved: resolved.get(spot.id),
          nearestOffsetKm: treatment === "nearby" ? 4.5 : 0,
          note,
        },
      ];
    }),
  );
  const manifest = {
    schemaVersion: 1,
    kind: "wave",
    model: model.id,
    modelName: model.name,
    provider: SYNTHETIC.provider,
    modelDetail: `${model.name} shaped sample bundle`,
    resolutionKm: model.resolutionKm,
    resolutionLabel: `${grid.dx}° sample grid`,
    run,
    runTime: iso(runMs),
    generatedAt: iso(runMs),
    stepHours: model.stepHours,
    grid,
    variables: Object.fromEntries(
      Object.entries(WAVE_VARIABLES).map(([name, variable]) => [
        name,
        {
          units: variable.units,
          label: variable.label,
          description: variable.description,
        },
      ]),
    ),
    frames,
    spotSeries: series,
    spotCoverage: coverage,
    directionConvention:
      "Wave directions are the bearing waves travel FROM, in degrees true, like the wind direction rows: 270° is a westerly swell running east.",
    partitionNote:
      "swh/pp1d/mwd describe the whole spectrum; shww/mpww/mdww are the wind sea and swell1_* the first swell partition. These are sample values, not a sea state.",
    ...provenance(),
  };
  return { manifest, files };
}

function weatherBundle(model, spots, runMs, grid) {
  const run = runId(runMs);
  const hours = frameHours(model);
  const prefix = `${model.id}-${run}-${hours[hours.length - 1]}h-v1`;
  const names = Object.keys(WEATHER_VARIABLES);
  const gridded = model.frameVariables;
  const series = Object.fromEntries(spots.map((spot) => [spot.id, []]));
  const frames = [];
  const files = [];
  hours.forEach((hour, index) => {
    const valid = iso(runMs + hour * HOUR);
    const interval = index === 0 ? null : [hours[index - 1], hour];
    const planes = {};
    names.forEach((name, order) => {
      const variable = WEATHER_VARIABLES[name];
      if (variable.spec)
        planes[name] = plane(
          grid,
          variable.spec,
          hour,
          model.seed + order * 0.09,
        );
    });
    // The accumulation is monotone in lead time; the interval amount differences it.
    const accumulated = (h) =>
      round(1.4 * (h / 3) * (0.6 + 0.4 * Math.abs(osc(h, 17, 0.2))), 1);
    const value = (name, x, y, code) => {
      const variable = WEATHER_VARIABLES[name];
      if (name === "ww") return code;
      if (variable.accumulation) return accumulated(hour);
      if (variable.differenced)
        return index === 0
          ? null
          : round(accumulated(hour) - accumulated(hours[index - 1]), 1);
      return round(planeAt(planes[name], x, y), variable.decimals);
    };
    const fields = {};
    for (const name of gridded) {
      const variable = WEATHER_VARIABLES[name];
      if (name === "ww")
        fields[name] = new Array(grid.width * grid.height)
          .fill(0)
          .map((_, i) => WEATHER_CODES[(i + index) % WEATHER_CODES.length]);
      else if (variable.accumulation || variable.differenced)
        fields[name] = new Array(grid.width * grid.height).fill(
          value(name, 0, 0, 0),
        );
      else fields[name] = field(grid, planes[name], variable.decimals);
      bounded(fields[name], 100000, null, `${model.id} ${name}`);
    }
    const payload = {
      model: model.id,
      run,
      hour,
      validTime: valid,
      grid,
      precipIntervalHours: interval,
      ...fields,
    };
    const url = `weather/${prefix}/${pad(hour, 3)}-${digestOf(payload)}.json`;
    files.push([url, payload]);
    frames.push({ hour, validTime: valid, url, precipIntervalHours: interval });
    spots.forEach((spot, order) => {
      const x = spotX(grid, spot.lon);
      const y = spotY(grid, spot.lat);
      const code = WEATHER_CODES[(order + index) % WEATHER_CODES.length];
      series[spot.id].push({
        hour,
        validTime: valid,
        precipIntervalHours: interval,
        values: Object.fromEntries(
          names.map((name) => [name, value(name, x, y, code)]),
        ),
      });
    });
  });
  const manifest = {
    schemaVersion: 1,
    kind: "weather",
    model: model.id,
    modelName: model.name,
    provider: SYNTHETIC.provider,
    modelDetail: `${model.name} shaped sample bundle`,
    resolutionKm: model.resolutionKm,
    resolutionLabel: `${grid.dx}° sample grid`,
    run,
    runTime: iso(runMs),
    generatedAt: iso(runMs),
    stepHours: model.stepHours,
    grid,
    variables: Object.fromEntries(
      names.map((name) => {
        const variable = WEATHER_VARIABLES[name];
        return [
          name,
          {
            units: variable.units,
            label: variable.label,
            description: variable.description,
            ...(variable.kind ? { kind: variable.kind } : {}),
          },
        ];
      }),
    ),
    frameVariables: [...gridded],
    frames,
    spotSeries: series,
    precipitationNote:
      "tp is the accumulation since initialization; precip is the amount in the interval ending at each step, obtained by differencing it and null at initialization, which has no interval. Each frame and series step declares that interval in precipIntervalHours.",
    seaTemperatureNote:
      "tg is a ground/skin temperature. Over sea it would be a model SST proxy, never an observation; here it is a sample value and not a measurement of anything.",
    presentWeatherNote:
      "ww is a WMO present-weather code, not a measurement: it belongs to the cell containing a location and is never interpolated, averaged or blended between models.",
    ...provenance(),
  };
  return { manifest, files };
}

