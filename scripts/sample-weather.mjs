#!/usr/bin/env node
/**
 * Deterministic SYNTHETIC forecast bundles in the published Force5 format.
 *
 * Real forecast output is never committed (see .gitignore: public/weather/), so
 * the test suites need data of their own. This writes small bundles that are
 * byte-for-byte in the published contract — the same schemaVersion 2 pointer,
 * the same run directory named for its content, the same frames and per-spot
 * series in their spot squares (scripts/runs.mjs, after force5/ingest/rundir.py)
 * — carrying a smooth analytic field instead of a forecast. Every manifest says
 * so in its provider and attribution, so a bundle can never be mistaken for
 * model output.
 *
 * Wind frames are written in the published binary encoding ("f5-int16-v1",
 * scripts/f5bin.mjs) for every model but ARPEGE, which stays on JSON frames so
 * that the readers' legacy path keeps a fixture of its own. Wave and weather
 * frames are JSON, as they are in production.
 *
 *   npm run weather:fixtures     the committed fixtures the unit tests read
 *   npm run weather:sample       the same bundles in public/weather, for local
 *                                development against a checkout with no ingest
 *   scripts/e2e-site.mjs         the same bundles in .e2e/public/weather, which
 *                                is the only weather the e2e site is built from
 *
 * Options: --profile fixtures|live, --out <dir>, --spacing <degrees of
 * longitude; latitude follows at DY_RATIO of it>, --now <iso>, --all (include
 * the models no test needs), --force.
 *
 * The output directory is never written over anything that could be a forecast.
 * A `*.json` manifest OR a run directory is enough to stop the write, because a
 * real import that was interrupted leaves run directories with no manifest at
 * all, and dropping synthetic manifests beside them would both corrupt the site
 * and make the ingest's prune treat the real runs as junk. `--force` lifts that,
 * but still refuses to delete a run directory unless a manifest in the same
 * directory claims it and says `provider: "Synthetic sample data"`.
 *
 * Two profiles differ in their run times:
 *   fixtures  a fixed sample calendar, so both suites are reproducible. The e2e
 *             specs pin their clocks to these run times — and rely on the gap
 *             between the wind runs and the later wave and surface runs — so
 *             the e2e sample set uses this profile too.
 *   live      run times derived from the wall clock, for a demo build that
 *             should read as fresh (see freshness() in force5/src/weather.ts).
 *
 * How the fields are built, and why it matters
 * --------------------------------------------
 * Every gridded field is affine in longitude and latitude at each step:
 *
 *     value(lon, lat) = a + bx · x + by · y,    x, y = grid index coordinates
 *
 * with a, bx and by quantised to whole hundredths and oscillating smoothly in
 * time. Bilinear interpolation reproduces an affine field exactly, so the
 * per-spot series this script publishes are the analytic values and agree with
 * `sample()` in force5/src/weather.ts to well inside the 0.005 rounding
 * tolerance the tests allow — without this script owning a second copy of the
 * sampler that could drift away from the browser's. The only sampling logic
 * here is which four cells a location falls between, which decides whether a
 * land-masked wave cell makes a spot read null; that mirrors the same four
 * lines in `sample()`.
 *
 * Every grid is rectangular — dx ≠ dy, in the proportion the real HARMONIE grid
 * has — because a square one cannot catch a sampler that divides longitude by
 * dy. Present weather is the exception to the affine rule: it is a code table,
 * read from the cell containing a location and never interpolated.
 */
