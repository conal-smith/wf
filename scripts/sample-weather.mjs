/** The published display box; every riding location sits well inside it. */
const BOX = { west: -11.0, east: -5.0, north: 56.0, south: 51.0 };

const round = (value, decimals) => {
  const factor = 10 ** decimals;
  return Math.round(value * factor) / factor;
};
const q2 = (value) => round(value, 2);
const q3 = (value) => round(value, 3);
const iso = (ms) => new Date(ms).toISOString().replace(".000Z", "Z");
const pad = (value, width) => String(value).padStart(width, "0");
const runId = (ms) => {
  const at = new Date(ms);
  return (
    `${at.getUTCFullYear()}${pad(at.getUTCMonth() + 1, 2)}` +
    `${pad(at.getUTCDate(), 2)}${pad(at.getUTCHours(), 2)}`
  );
};

/**
 * How much shorter a grid's rows are than its columns.
 *
 * The real HARMONIE grid is 0.025° × 0.02°, and a square sample grid is a test
 * that cannot fail: with dx === dy a sampler that divided longitude by dy would
 * agree with every fixture. So every sample grid is rectangular in the same
 * proportion the production one is.
 */
const DY_RATIO = 0.8;

/**
 * A regular grid covering the display box at the given longitude spacing.
 *
 * The cell counts are rounded up and the east and south edges then restated from
 * them, so the grid describes itself exactly — `east - west === (width - 1) · dx`
 * to the browser's tolerance — for any spacing, without dx and dy having to
 * divide the box.
 */
function gridAt(dx, dy = q3(dx * DY_RATIO)) {
  const width = Math.ceil((BOX.east - BOX.west) / dx) + 1;
  const height = Math.ceil((BOX.north - BOX.south) / dy) + 1;
  return {
    width,
    height,
    west: BOX.west,
    east: q3(BOX.west + (width - 1) * dx),
    north: BOX.north,
    south: q3(BOX.north - (height - 1) * dy),
    dx,
    dy,
    order: "north-to-south, west-to-east",
  };
}

const osc = (hour, period, phase) =>
  Math.sin(2 * Math.PI * (hour / period + phase));

/**
 * One field at one step, as an affine plane in grid-index space. The three
 * coefficients are whole hundredths, so every grid node is exactly a published
 * two-decimal value and the plane a reader recovers by interpolation is the
 * plane that was written.
 */
function plane(grid, spec, hour, seed) {
  const p = {
    a: q2(spec.base + spec.amp * osc(hour, spec.period, seed + spec.phase)),
    bx: q2(
      spec.gx *
        osc(hour, spec.period * 1.7, seed + spec.phase + 0.19) *
        grid.dx,
    ),
    by: q2(
      spec.gy *
        osc(hour, spec.period * 2.3, seed + spec.phase + 0.41) *
        grid.dy,
    ),
  };
  // `floor` slides the whole plane so its lowest grid node is exactly that
  // value. An affine field takes its minimum at a corner, so this is a shift of
  // `a` by a multiple of a hundredth: the plane stays affine and every node
  // stays exactly published, and one cell of the field reads the floor exactly.
  // Cloud uses it, so a published zero is a real zero rather than a rounding
  // artefact — the readers have to keep telling "none" apart from "no data".
  if (spec.floor !== undefined)
    p.a = q2(
      p.a -
        (p.a +
          Math.min(0, p.bx * (grid.width - 1)) +
          Math.min(0, p.by * (grid.height - 1))) +
        spec.floor,
    );
  return p;
}

const planeAt = (p, x, y) => p.a + p.bx * x + p.by * y;
const spotX = (grid, lon) => (lon - grid.west) / grid.dx;
const spotY = (grid, lat) => (grid.north - lat) / grid.dy;

/** Field values over the whole grid, rows north-to-south, columns west-to-east. */
function field(grid, p, decimals = 2, mask = null) {
  const values = new Array(grid.width * grid.height);
  for (let j = 0; j < grid.height; j++)
    for (let i = 0; i < grid.width; i++) {
      const index = j * grid.width + i;
      values[index] = mask?.[index] ? null : round(planeAt(p, i, j), decimals);
    }
  return values;
}

/**
 * The four cells a location falls between, exactly as `sample()` picks them.
 * Used only to decide whether a masked wave cell makes a spot read null.
 */
function corners(grid, lon, lat) {
  const x = spotX(grid, lon);
  const y = spotY(grid, lat);
  if (x < 0 || y < 0 || x > grid.width - 1 || y > grid.height - 1) return null;
  const x0 = Math.min(Math.floor(x), grid.width - 2);
  const y0 = Math.min(Math.floor(y), grid.height - 2);
  const i = y0 * grid.width + x0;
  return [i, i + 1, i + grid.width, i + grid.width + 1];
}

/** Every published value is checked against the contract's own bounds. */
function bounded(values, limit, minimum, what) {
  for (const value of values) {
    if (value === null) continue;
    if (!Number.isFinite(value) || Math.abs(value) > limit)
      throw new Error(`${what}: ${value} is outside ±${limit}`);
    if (minimum !== null && value < minimum)
      throw new Error(`${what}: ${value} is below ${minimum}`);
  }
  return values;
}

