/**
 * The run a live bundle publishes: the most recent whole cycle a real adapter
 * would already have finished, so the site reads the bundle as fresh and the
 * scrubber opens part-way through the run rather than at its first frame.
 */
function liveRun(nowMs, cycleHours, lagHours) {
  const cycle = cycleHours * HOUR;
  return Math.floor((nowMs - lagHours * HOUR) / cycle) * cycle;
}

function build({ profile, now, spacing, all }) {
  const spots = JSON.parse(
    readFileSync(join(ROOT, "public", "riding-locations.json"), "utf8"),
  );
  const bundles = [];
  for (const model of CATALOGUE) {
    if (model.optional && !all) continue;
    const shaped =
      profile === "fixtures" ? model : { ...model, ...(model.live ?? {}) };
    const runMs =
      profile === "fixtures"
        ? Date.parse(FIXTURE_RUNS[model.id])
        : liveRun(now, model.stepHours === 6 ? 6 : 3, 3);
    const grid = gridAt(spacing ?? model.spacing[profile]);
    const { manifest, files, prefix } = BUILDERS[model.kind](
      shaped,
      spots,
      runMs,
      grid,
    );
    // Published as the pipeline publishes a run: frames and spot squares in a
    // directory named for their content, and a small pointer beside it.
    const published = publishRun(
      manifest,
      prefix,
      files.map(([url, body], index) => [
        manifest.frames[index].hour,
        url.endsWith(".bin") ? "bin" : "json",
        body,
      ]),
      spots,
    );
    bundles.push({
      model: shaped,
      manifest: published.pointer,
      files: published.files,
    });
  }
  return bundles;
}

/**
 * Anything in the output directory that looks like forecast data.
 *
 * Not "one of our nine manifest names": a real `weather:refresh` writes one
 * manifest and one run directory at a time, and an import interrupted before it
 * replaced the pointer manifests leaves run directories with no manifest at all.
 * Either way the directory holds a real run, and writing synthetic bundles
 * beside it would both corrupt the site and hand the ingest's prune a set of
 * directories no manifest claims — which it would then delete as junk.
 */
function forecastData(out) {
  if (!existsSync(out)) return [];
  return readdirSync(out, { withFileTypes: true })
    .filter(
      (entry) =>
        (entry.isFile() && entry.name.endsWith(".json")) || entry.isDirectory(),
    )
    .map((entry) => entry.name)
    .sort();
}

/** Whether a run directory's own manifest says this script wrote it. */
function syntheticRun(out, name) {
  // A run directory is named `<model>-<run>-<horizon>h-v1-<hash>`; its manifest
  // is the bundle file for that model, which says in plain words what the data
  // is, and names the directory as its `base`.
  const model = /^(.+)-\d{10}-\d+h-v\d+-[0-9a-f]{8}$/.exec(name)?.[1];
  if (!model) return false;
  for (const file of readdirSync(out)) {
    if (!file.endsWith(".json")) continue;
    let manifest;
    try {
      manifest = JSON.parse(readFileSync(join(out, file), "utf8"));
    } catch {
      continue;
    }
    if (manifest?.model !== model) continue;
    return (
      manifest.provider === SYNTHETIC.provider && manifest.base === `${name}/`
    );
  }
  return false;
}

function write(bundles, out, { force }) {
  const found = forecastData(out);
  if (found.length && !force)
    throw new Error(
      `${out} already holds ${found.join(", ")}. Refusing to touch forecast ` +
        "data; pass --force to replace it, or --out <dir> to write elsewhere.",
    );
  // `weather/<prefix>/…` in a frame url is relative to the directory above the
  // manifest, which is how the site and the publisher both resolve it.
  const root = resolve(out, "..");
  const runDirectory = ({ files }) =>
    files.length ? join(root, "weather", files[0][0].split("/")[1]) : null;
  // A run directory is replaced whole, never merged — but only when the bundle
  // beside it says this script wrote it. A real run whose name happens to match
  // (the `live` profile anchors its runs to the wall clock, so one will) is data
  // somebody fetched, and --force is not a licence to delete it. Every directory
  // is checked before anything at all is written: a refusal half way through
  // would leave exactly the mixture of real and synthetic this is here to stop.
  const replacing = bundles.map(runDirectory).filter(Boolean);
  for (const prefix of replacing) {
    if (!existsSync(prefix)) continue;
    if (!syntheticRun(out, prefix.split("/").pop()))
      throw new Error(
        `${prefix} exists and no manifest in ${out} claims it as ` +
          `"${SYNTHETIC.provider}". Refusing to delete it.`,
      );
  }

  let bytes = 0;
  const save = (path, value) => {
    const body = Buffer.isBuffer(value) ? value : JSON.stringify(value);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, body);
    bytes += Buffer.byteLength(body);
  };
  // The run directory a synthetic pointer being replaced named, when it names
  // another one: its content changed, so its name did too, and nothing else
  // will ever claim it. Real runs are never named by a synthetic pointer.
  const superseded = bundles.flatMap((bundle) => {
    let previous;
    try {
      previous = JSON.parse(readFileSync(join(out, bundle.model.file), "utf8"));
    } catch {
      return [];
    }
    const name = String(previous?.base ?? "").replace(/\/$/, "");
    return previous?.provider === SYNTHETIC.provider &&
      name &&
      `${name}/` !== bundle.manifest.base &&
      syntheticRun(out, name)
      ? [join(root, "weather", name)]
      : [];
  });
  for (const directory of superseded)
    if (existsSync(directory)) rmSync(directory, { recursive: true });
  for (const bundle of bundles) {
    const prefix = runDirectory(bundle);
    if (prefix && existsSync(prefix)) rmSync(prefix, { recursive: true });
    for (const [url, payload] of bundle.files) save(join(root, url), payload);
    save(join(out, bundle.model.file), bundle.manifest);
  }
  return bytes;
}

function main() {
  const args = process.argv.slice(2);
  const option = (name, fallback) => {
    const index = args.indexOf(`--${name}`);
    return index === -1 ? fallback : args[index + 1];
  };
  const profile = option("profile", "fixtures");
  if (profile !== "fixtures" && profile !== "live")
    throw new Error("Use --profile fixtures or --profile live");
  const out = resolve(ROOT, option("out", "public/weather"));
  const nowOption = option("now", null);
  const now = nowOption ? Date.parse(nowOption) : Date.now();
  if (!Number.isFinite(now)) throw new Error(`Unreadable --now ${nowOption}`);
  const spacing =
    option("spacing", null) === null ? null : Number(option("spacing"));
  if (spacing !== null && !(spacing > 0))
    throw new Error("--spacing must be positive");
  const all = args.includes("--all");
  const bundles = build({ profile, now, spacing, all });
  const bytes = write(bundles, out, { force: args.includes("--force") });
  const frames = bundles.reduce(
    (total, bundle) => total + bundle.files.length,
    0,
  );
  console.log(
    `Wrote ${bundles.length} synthetic ${profile} bundles (${frames} frames, ` +
      `${(bytes / 1024).toFixed(0)} KiB) to ${out}`,
  );
}

try {
  main();
} catch (error) {
  console.error(`Sample weather generation failed: ${error.message}`);
  process.exit(1);
}
